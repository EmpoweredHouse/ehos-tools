defmodule EhosDiagrams.GeneratorTest do
  # Moved from eh-os's Mix.Tasks.Ehos.Gen.DiagramsTest with the code (T-21).
  use ExUnit.Case, async: true

  alias EhosDiagrams.Generator

  @moduletag :tmp_dir

  @vocabulary %{words: ["application"], alone: [], concepts: %{}, badges: []}

  @source """
  <!-- title: An application -->
  <!-- desc: One application. -->
  <!-- words: application -->
  <!-- parts: client = - -->
  <svg viewBox="0 0 200 100" xmlns="http://www.w3.org/2000/svg">
  <rect id="client-client" class="n-back" x="20" y="20" width="120" height="60"/>
  <text class="name" x="80" y="50">Application</text>
  </svg>
  """

  setup %{tmp_dir: dir} do
    sources = Path.join(dir, "diagrams")
    out = Path.join(dir, "img")
    page = Path.join(dir, "page.md")
    File.mkdir_p!(sources)
    File.write!(Path.join(sources, "client.svg"), @source)
    File.write!(page, "![One application](img/client.svg)\n")

    config = [
      sources: sources,
      out: out,
      vocabulary: @vocabulary,
      pages: [page],
      documents: [page]
    ]

    %{config: config, out: out, design: EhosDiagrams.design("../ehos_design/priv")}
  end

  test "writes an output and the fonts' licences beside it, and then checks them", %{
    config: config,
    out: out,
    design: design
  } do
    assert Generator.run(config, false, design) ==
             {:ok, "1 diagrams in #{out} are up to date"}

    # Named from the current directory, so no machine's own path is written into an output.
    source = Path.relative_to_cwd(Path.join(config[:sources], "client.svg"))
    refute source =~ ~r{\A/}

    assert File.read!(Path.join(out, "client.svg")) =~
             "Generated by `mix ehos_diagrams.gen` from #{source}. Do not edit."

    assert File.exists?(Path.join(out, "OFL-albert-sans.txt"))
    assert File.exists?(Path.join(out, "OFL-jetbrains-mono.txt"))
    assert Generator.run(config, true, design) == {:ok, "1 diagrams in #{out} are up to date"}
  end

  test "a check fails on an output edited by hand, and writing puts it back", %{
    config: config,
    out: out,
    design: design
  } do
    Generator.run(config, false, design)
    output = Path.join(out, "client.svg")
    written = File.read!(output)
    File.write!(output, String.replace(written, "Application", "Platform"))

    assert Generator.run(config, true, design) ==
             {:error,
              "#{output} differ from their sources. Run `mix ehos_diagrams.gen` and commit them."}

    Generator.run(config, false, design)
    assert File.read!(output) == written
  end

  test "fails on a source that holds what is refused", %{config: config, design: design} do
    source = Path.join(config[:sources], "client.svg")
    File.write!(source, String.replace(@source, "</svg>", "<script>alert(1)</script></svg>"))

    assert Generator.run(config, false, design) ==
             {:error, "#{source} holds the element <script>"}
  end

  test "a check fails on an output with no source, and writing removes it", %{
    config: config,
    out: out,
    design: design
  } do
    Generator.run(config, false, design)
    gone = Path.join(out, "gone.svg")

    File.write!(
      gone,
      ~s(<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by `x` from gone.svg. -->\n)
    )

    assert Generator.run(config, true, design) == {:error, "#{gone} has no source"}

    Generator.run(config, false, design)
    refute File.exists?(gone)
  end

  test "leaves an SVG made by hand beside the outputs alone", %{
    config: config,
    out: out,
    design: design
  } do
    logo = Path.join(out, "logo.svg")
    File.mkdir_p!(out)
    File.write!(logo, ~s(<svg xmlns="http://www.w3.org/2000/svg"/>\n))

    assert Generator.run(config, false, design) == {:ok, "1 diagrams in #{out} are up to date"}
    assert Generator.run(config, true, design) == {:ok, "1 diagrams in #{out} are up to date"}
    assert File.exists?(logo)
  end

  test "asks no page to link an output when the host names no pages", %{
    config: config,
    out: out,
    design: design
  } do
    config = Keyword.delete(config, :pages)
    File.write!(hd(config[:documents]), "No image here.\n")

    assert Generator.run(config, false, design) == {:ok, "1 diagrams in #{out} are up to date"}
  end

  test "finds no orphan in an output directory named from the current one", %{
    config: config,
    design: design
  } do
    out = "./" <> Path.relative_to_cwd(config[:out])
    config = Keyword.put(config, :out, out)
    Generator.run(config, false, design)

    assert Generator.run(config, true, design) == {:ok, "1 diagrams in #{out} are up to date"}
  end

  test "asks no page to link an output when the host names an empty list of pages", %{
    config: config,
    out: out,
    design: design
  } do
    config = Keyword.put(config, :pages, [])
    File.write!(hd(config[:documents]), "No image here.\n")

    assert Generator.run(config, false, design) == {:ok, "1 diagrams in #{out} are up to date"}
  end

  test "refuses sources outside the current directory, whose path an output would name", %{
    config: config,
    design: design
  } do
    # A directory that exists, outside this package.
    outside = Path.expand("../ehos_design/priv/css")
    config = Keyword.put(config, :sources, outside)

    assert Generator.run(config, false, design) ==
             {:error, "#{outside}, a directory of sources outside #{File.cwd!()}"}
  end

  test "refuses to write the outputs over their sources", %{config: config, design: design} do
    config = Keyword.put(config, :out, config[:sources] <> "/")

    assert Generator.run(config, false, design) ==
             {:error, "#{config[:out]}, the sources' own directory, for the outputs"}

    assert File.read!(Path.join(config[:sources], "client.svg")) == @source
  end

  test "refuses outputs written through a link to the sources' directory", %{
    config: config,
    tmp_dir: dir,
    design: design
  } do
    link = Path.join(dir, "linked")
    File.ln_s!(config[:sources], link)
    config = Keyword.put(config, :out, link)

    assert Generator.run(config, false, design) ==
             {:error, "#{link}, the sources' own directory, for the outputs"}

    assert File.read!(Path.join(config[:sources], "client.svg")) == @source
  end

  test "refuses an output that is a link, rather than write over what it points at", %{
    config: config,
    out: out,
    design: design
  } do
    source = Path.join(config[:sources], "client.svg")
    output = Path.join(out, "client.svg")
    File.mkdir_p!(out)
    File.ln_s!(source, output)

    assert Generator.run(config, false, design) ==
             {:error, "#{output}, a link, which writing the output would follow"}

    File.rm!(output)
    File.ln!(source, output)

    assert Generator.run(config, false, design) ==
             {:error, "#{output}, a link, which writing the output would follow"}

    assert File.read!(source) == @source

    # A licence kept as a link is no output of a source.
    File.rm!(output)
    licence = Path.join(out, "OFL-albert-sans.txt")

    File.ln_s!(
      Path.expand("../ehos_design/priv/static/ehos_design/fonts/OFL-albert-sans.txt"),
      licence
    )

    assert Generator.run(config, false, design) == {:ok, "1 diagrams in #{out} are up to date"}
  end

  test "refuses a licence that links to another file, rather than write over it", %{
    config: config,
    out: out,
    tmp_dir: dir,
    design: design
  } do
    mine = Path.join(dir, "mine.txt")
    File.write!(mine, "not a licence")
    File.mkdir_p!(out)
    licence = Path.join(out, "OFL-albert-sans.txt")
    File.ln_s!(mine, licence)

    assert Generator.run(config, false, design) ==
             {:error, "#{licence}, a link, which writing the output would follow"}

    assert File.read!(mine) == "not a licence"
  end

  test "refuses an outputs' directory that is a link, rather than write where it points", %{
    config: config,
    tmp_dir: dir,
    design: design
  } do
    elsewhere = Path.join(dir, "elsewhere")
    File.mkdir_p!(elsewhere)
    link = Path.join(dir, "img-link")
    File.ln_s!(elsewhere, link)
    config = Keyword.put(config, :out, link)

    assert Generator.run(config, false, design) ==
             {:error, "#{link}, a link, which writing the outputs would follow"}

    assert File.ls!(elsewhere) == []
  end

  test "refuses sources whose path holds \"--\", which an output's first comment cannot", %{
    config: config,
    tmp_dir: dir,
    design: design
  } do
    sources = Path.join(dir, "dia--grams")
    File.mkdir_p!(sources)
    File.cp!(Path.join(config[:sources], "client.svg"), Path.join(sources, "client.svg"))
    config = Keyword.put(config, :sources, sources)

    assert Generator.run(config, false, design) ==
             {:error, "#{sources}, a path an output names in a comment, which cannot hold \"--\""}
  end

  test "refuses a sources directory that holds no source, rather than remove every output", %{
    config: config,
    out: out,
    design: design
  } do
    Generator.run(config, false, design)
    File.rm!(Path.join(config[:sources], "client.svg"))

    assert Generator.run(config, false, design) ==
             {:error, "#{config[:sources]}, which holds no source"}

    assert File.exists?(Path.join(out, "client.svg"))
  end

  test "refuses a sources directory that is not there, rather than remove every output", %{
    config: config,
    out: out,
    design: design
  } do
    Generator.run(config, false, design)
    gone = Keyword.put(config, :sources, config[:sources] <> "-gone")

    assert Generator.run(gone, false, design) ==
             {:error, "#{gone[:sources]}, which is not a directory of sources"}

    assert File.exists?(Path.join(out, "client.svg"))
  end

  test "fails on an output no page links, and on a Mermaid block", %{
    config: config,
    out: out,
    design: design
  } do
    page = hd(config[:pages])
    File.write!(page, "```mermaid\nflowchart LR\n```\n")

    assert Generator.run(config, false, design) ==
             {:error,
              "#{out}/client.svg is linked from no page\n" <>
                "#{page} holds a Mermaid block (eh-os D-107)"}
  end

  test "takes the vocabulary from a function of the host", %{config: config, design: design} do
    config = Keyword.put(config, :vocabulary, {Map, :put, [@vocabulary, :words, []]})

    assert Generator.run(config, false, design) ==
             {:error,
              "#{config[:sources]}/client.svg holds the word application, which is not in the glossary"}
  end
end
