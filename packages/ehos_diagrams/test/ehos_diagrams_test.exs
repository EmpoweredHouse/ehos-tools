    test "the legend and the key are one each and hold only swatches", %{design: design} do
      hidden =
        ~s(<g class="legend"><rect class="n-back m-open" x="40" y="120" width="120" height="60"/></g>)

      assert refused(source(@part <> "\n" <> hidden), design) =~ "larger than a swatch"

      two = ~s(<g class="key"><text class="keyt" x="1" y="190">a</text></g>
<g class="key"><text class="keyt" x="1" y="195">b</text></g>)
      assert refused(source(@part <> "\n" <> two), design) =~ "2 groups of class key"
    end

    test "a source with many tags is refused for its size, quickly", %{design: design} do
      tags = for i <- 1..2_000, do: ~s(<text class="tagt" x="#{rem(i, 100)}" y="50">OPEN</text>\n)

      {time, reasons} =
        :timer.tc(fn -> refused(source(@part <> "\n" <> Enum.join(tags)), design) end)

      assert reasons =~ "2001 parts, chips and tags, more than 200"
      assert time < 5_000_000
    end

    test "a source with many labels and masks is refused for its size, quickly", %{
      design: design
    } do
      labels =
        for i <- 1..2_000,
            do:
              ~s(<rect class="mask" x="#{i}" y="0" width="1" height="1"/><text class="lbl" x="0" y="#{i}">A</text>\n)

      {time, reasons} =
        :timer.tc(fn -> refused(source(@part <> "\n" <> Enum.join(labels)), design) end)

      assert reasons =~ "4000 masks and labels, more than 200"
      assert time < 5_000_000
    end

    test "a source with many swatches in its legend is refused for its size, quickly", %{
      design: design
    } do
      masks = for i <- 1..150, do: ~s(<rect class="mask" x="#{i}" y="0" width="1" height="1"/>\n)

      swatches =
        for i <- 1..2_000, do: ~s(<rect class="n-back" x="#{i}" y="300" width="9" height="9"/>)

      body = Enum.join(masks) <> ~s(<g class="legend">#{Enum.join(swatches)}</g>)
      {time, reasons} = :timer.tc(fn -> refused(source(@part <> "\n" <> body), design) end)

      assert reasons =~ "2001 parts, chips and tags, more than 200"
      assert time < 5_000_000
    end

    test "a header's entry is short, and its lists are bounded", %{design: design} do
      long = String.duplicate("a", 33_000)
      assert refused(source(@part, words: long), design) =~ "an entry longer than 120 characters"

      # One grapheme of 60 KB: a's with combining accents, still too long for a pattern.
      accented = "a" <> String.duplicate("\u0301", 30_000)

      assert refused(source(@part, verbs: accented), design) =~
               "an entry longer than 120 characters"

      many = Enum.map_join(1..65, ", ", &"word#{&1}")
      assert refused(source(@part, technical: many), design) =~ "more than 64 entries"
    end

    test "the legend hides no badge: no tag over a part, no class off a group, no unsized part",
         %{design: design} do
      over = ~s(<g class="legend"><text class="tagt" x="44" y="50">OPEN</text></g>)

      assert refused(source(@part <> "\n" <> over), design) =~
               "a tag of the legend or the key drawn over"

      aside = ~s(<g class="legend"><text class="tagt" x="300" y="190">OPEN</text></g>)
      assert {:ok, _svg} = render(source(@part <> "\n" <> aside), design)

      text = ~s(<text class="legend" x="300" y="190">x</text>)
      assert refused(source(@part <> "\n" <> text), design) =~ "the class legend or key on <text>"

      sized =
        ~s(<g class="legend"><rect class="n-back m-open" x="40" y="120" width="300px" height="60"/></g>)

      assert refused(source(@part <> "\n" <> sized), design) =~
               "whose width and height are not numbers"
    end

    test "a <use> copies nothing the checks read, alone or in a group", %{design: design} do
      for body <- [
            ~s(<use href="#test-client" x="200"/>),
            ~s(<g id="test-group">#{@connector}</g>\n<use href="#test-group" y="40"/>),
            ~s(<g class="ring"><path id="test-p" d="M 10 10 L 10 50"/></g>\n<use href="#test-p" x="100"/>),
            ~s(<rect id="test-m" class="mask" x="1" y="150" width="9" height="9"/>\n<use xlink:href="#test-m"/>),
            ~s(<text id="test-n" class="sub" x="1" y="190">a</text>\n<use href="#test-n" x="200"/>)
          ] do
        assert refused(source(@part <> "\n" <> body), design) =~
                 "a <use> that copies what the checks read",
               body
      end

      knock = ~s(<defs><rect id="test-k" class="knock" x="1" y="1" width="9" height="9"/></defs>
<use href="#test-k" x="200"/>)

      assert {:ok, _svg} = render(source(@part <> "\n" <> knock), design)
    end

    test "a reference holds nothing after its id, not even a newline", %{design: design} do
      assert refused(source(@part <> ~s(\n<use href="#test-client&#10;"/>)), design) =~
               "the reference"
    end

    test "a header names a part once, and a source draws it once", %{design: design} do
      assert refused(source(@part, parts: "client = built-one, client = -"), design) =~
               "the part client twice in its header"

      again = ~s(<rect id="test-client" class="n-back" x="200" y="40" width="60" height="60"/>)
      assert refused(source(@part <> "\n" <> again), design) =~ "the part client drawn 2 times"

      doubled =
        source(@part) |> String.replace("<!-- verbs:", "<!-- words: operator -->\n<!-- verbs:")

      assert refused(doubled, design) =~ "two words lines in its header"
    end

    test "a chip and a connector's label are words of the header, technical or its verbs", %{
      design: design
    } do
      assert {:ok, _svg} = render(source(@part <> "\n" <> @connector), design)

      assert refused(source(@part <> "\n" <> @connector, verbs: ""), design) =~
               "the connector label SUBMITS, which is neither a word of its header, technical nor one of its verbs"

      chip = ~s(<text class="chipt" x="60" y="90">Stream</text>)

      assert refused(source(@part <> "\n" <> chip), design) =~
               "the chip Stream, which is neither a word of its header nor technical"

      assert {:ok, _svg} = render(source(@part <> "\n" <> chip, technical: "Stream"), design)
    end

    test "no text shows a word the glossary says is never read alone", %{design: design} do
      sub = ~s(<text class="sub" x="60" y="90">made from a template</text>)
      assert refused(source(@part <> "\n" <> sub), design) =~ ~s("template" alone in)

      qualified = ~s(<text class="sub" x="60" y="90">made from an environment template</text>)
      assert {:ok, _svg} = render(source(@part <> "\n" <> qualified), design)

      embedded = ~s(<text class="sub" x="60" y="90">its xrole binding</text>)
      assert refused(source(@part <> "\n" <> embedded), design) =~ ~s("binding" alone in)

      plural = ~s(<text class="sub" x="60" y="90">two Resource Bindings</text>)
      assert {:ok, _svg} = render(source(@part <> "\n" <> plural), design)
    end
  end

  describe "the vocabulary's badges" do
    @tagged ~s(<rect id="test-client" class="n-back m-draft" x="40" y="40" width="120" height="60"/>
<text class="tagt" x="44" y="50">DRAFT</text>
<text class="name" x="100" y="70" text-anchor="middle">Client application</text>)

    test "are the host's: a class for each, outlined by its treatment", %{design: design} do
      vocabulary = %{
        @vocabulary
        | concepts: %{"draft-one" => "draft"},
          badges: [{"done", :none}, {"draft", :dotted}]
      }

      assert {:ok, svg} =
               EhosDiagrams.render(
                 source(@tagged, parts: "client = draft-one"),
                 "test",
                 design,
                 vocabulary
               )

      assert svg =~ "#test .m-draft{stroke-dasharray: 2 4}"

      assert {:error, reasons} =
               EhosDiagrams.render(
                 source(@tagged, parts: "client = -"),
                 "test",
                 design,
                 @vocabulary
               )

      assert "the class m-draft" in reasons
    end

    test "may be none, for a host with no maturity, whose parts stand for no concept", %{
      design: design
    } do
      vocabulary = %{@vocabulary | concepts: %{}, badges: []}

      assert {:ok, _svg} =
               EhosDiagrams.render(source(@part, parts: "client = -"), "test", design, vocabulary)

      assert EhosDiagrams.render(
               source(@part, parts: "client = built-one"),
               "test",
               design,
               vocabulary
             ) ==
               {:error, ["the part client, whose concept built-one its vocabulary does not hold"]}
    end

    test "are refused when one is not a lowercase word or has no treatment the skin knows", %{
      design: design
    } do
      for badges <- [[{"Built", :none}], [{"built\n", :none}], [{"built", :wavy}]] do
        assert_raise ArgumentError, ~r/a badge is a lowercase word/, fn ->
          EhosDiagrams.render(source(@part), "test", design, %{@vocabulary | badges: badges})
        end
      end
    end
  end

