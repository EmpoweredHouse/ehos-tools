defmodule EhosDiagramsTest do
  # Moved from eh-os's Ehos.Dev.DiagramsTest with the code (T-21); the issues it names are eh-os's.
  use ExUnit.Case, async: true

  @priv "../ehos_design/priv"

  doctest EhosDiagrams

  @vocabulary %{
    words: ["application", "governance plane", "operator", "resource binding"],
    alone: [
      {"binding", ["role binding", "resource binding"]},
      {"template", ["environment template"]}
    ],
    concepts: %{"built-one" => "built", "planned-one" => "planned", "open-one" => "open"},
    badges: [{"built", :none}, {"planned", :dashed}, {"open", :muted}]
  }

  setup_all do
    %{design: EhosDiagrams.design(@priv)}
  end

  # A source that holds nothing refused: one part, one connector on a mask's label.
  defp source(body, header \\ []) do
    header =
      Keyword.merge(
        [
          title: "A part",
          desc: "One part.",
          words: "application",
          technical: "Kubernetes",
          verbs: "submits",
          parts: if(body =~ ~s(id="test-client"), do: "client = built-one", else: "")
        ],
        header
      )

    lines = for {key, value} <- header, do: "<!-- #{key}: #{value} -->\n"

    IO.iodata_to_binary([
      lines,
      ~s(<svg viewBox="0 0 400 200" xmlns="http://www.w3.org/2000/svg">\n),
      body,
      "\n</svg>\n"
    ])
  end

  @part ~s(<rect id="test-client" class="n-back" x="40" y="40" width="120" height="60" rx="6"/>
<text class="name" x="100" y="70" text-anchor="middle">Client application</text>)

  @connector ~s(<line class="arr" x1="160" y1="70" x2="240" y2="70"/>
<rect class="mask" x="176" y="50" width="48" height="14" rx="2"/>
<text class="lbl" x="180" y="60">SUBMITS</text>)

  defp render(source, design), do: EhosDiagrams.render(source, "test", design, @vocabulary)

  defp refused(source, design) do
    assert {:error, reasons} = render(source, design)
    Enum.join(reasons, "\n")
  end

  describe "the skin" do
    test "is ehos_design's tokens, light over the stylesheet's dark root" do
      css = File.read!(Path.join(@priv, "css/colors_and_type.css"))

      light = EhosDiagrams.tokens(css, :light)
      dark = EhosDiagrams.tokens(css, :dark)

      assert light["canvas"] == "#F0EEE9"
      assert dark["canvas"] == "#0B0B0C"
      # var(--lime) and var(--lime-deep) are resolved, since an SVG holds no stylesheet of theirs.
      assert light["accent-ink"] == "#4A7314"
      assert dark["accent-ink"] == "#D0FF6D"
      assert light["sans"] =~ "Albert Sans"
    end
  end

  describe "a source that holds nothing refused" do
    test "is written as an accessible SVG in both themes", %{design: design} do
      assert {:ok, svg} = render(source(@part <> "\n" <> @connector), design)

      assert svg =~ ~s(role="img" aria-labelledby="test-title test-desc")
      assert svg =~ ~s(<title id="test-title">A part</title>)
      assert svg =~ ~s(<desc id="test-desc">One part.</desc>)
      assert svg =~ "@media (prefers-color-scheme: dark){#test{"
      assert svg =~ "<!-- Generated by `mix ehos_diagrams.gen` from test.svg. Do not edit. "
      assert render(source(@part <> "\n" <> @connector), design) == {:ok, svg}
    end

    test "embeds only the faces its text uses, and loads nothing", %{design: design} do
      assert {:ok, svg} = render(source(@part), design)

      # The name is Albert Sans at 500 and nothing else is text.
      assert [_one] = Regex.scan(~r/@font-face/, svg)
      assert svg =~ ~s(font-family:"Albert Sans";font-weight:500)
      refute svg =~ ~s(JetBrains Mono";font-weight)

      urls = Regex.scan(~r/(?:https?:|url\()([^)"\s]*)/, svg, capture: :all_but_first)

      assert Enum.all?(urls, fn [url] ->
               url == "//www.w3.org/2000/svg" or url =~ ~r/^data:font\/woff2;base64,/
             end)
    end

    test "has its text and its header escaped", %{design: design} do
      text =
        ~s(<text class="keyt" x="40" y="160">A &quot;quote&quot;, a &lt;tag&gt; and ]]&gt;</text>)

      header = [title: ~s(Say "this" & <that> ]]>)]

      assert {:ok, svg} = render(source(@part <> "\n" <> text, header), design)

      assert svg =~ "Say &quot;this&quot; &amp; &lt;that&gt; ]]&gt;"
      assert svg =~ "A &quot;quote&quot;, a &lt;tag&gt; and ]]&gt;"
      # What is written parses back.
      body = svg |> String.split("\n", parts: 3) |> List.last()
      assert {_doc, []} = :xmerl_scan.string(:binary.bin_to_list(body), quiet: true)
    end

    test "keeps text beside a tspan in its order", %{design: design} do
      text =
        ~s(<text class="keyt" x="40" y="160">Before <tspan class="sub">inside</tspan> after</text>)

      assert {:ok, svg} = render(source(@part <> "\n" <> text), design)
      assert svg =~ ~s(>Before <tspan class="sub">inside</tspan> after</text>)
    end
  end

  describe "a source is refused before it is parsed" do
    test "with a DTD that would read a file from the machine", %{design: design} do
      source =
        ~s(<!-- title: t -->\n<!-- desc: d -->\n<!DOCTYPE svg [<!ENTITY secret SYSTEM "file:///etc/passwd">]>\n) <>
          ~s(<svg viewBox="0 0 10 10" xmlns="http://www.w3.org/2000/svg"><text class="keyt" x="1" y="1">&secret;</text></svg>)

      assert refused(source, design) =~ "a DOCTYPE"
    end

    test "with an entity, a processing instruction, or another encoding", %{design: design} do
      assert refused(source(~s(<!ENTITY x "y">)), design) =~ "an ENTITY"

      assert refused(
               ~s(<?xml-stylesheet href="https://example.com/x.css"?>\n) <> source(""),
               design
             ) =~ "a processing instruction"

      assert refused(~s(<?xml version="1.0" encoding="UTF-16"?>\n) <> source(""), design) =~
               "an encoding other than UTF-8"
    end

    test "when it is not UTF-8, or starts with a byte-order mark", %{design: design} do
      utf16 = :unicode.characters_to_binary(source(@part), :utf8, {:utf16, :little})

      assert refused(utf16, design) =~ "not UTF-8"
      assert refused(<<0xFF, 0xFE>> <> utf16, design) =~ "not UTF-8"
      assert refused(<<0xC3, 0x28>> <> source(@part), design) =~ "not UTF-8"
      assert refused(<<0xEF, 0xBB, 0xBF>> <> source(@part), design) =~ "a byte-order mark"
    end

    test "when its header has no title or description", %{design: design} do
      assert refused(source(@part, title: ""), design) =~ "no title in its header"
    end
  end

  describe "a parsed source is refused" do
    test "for an element that runs or loads something", %{design: design} do
      for body <- [
            ~s{<script>alert(1)</script>},
            ~s(<foreignObject width="10" height="10"/>),
            ~s(<a href="#x"/>),
            ~s(<image href="https://example.com/x.png"/>),
            ~s(<style>rect{fill:red}</style>),
            ~s(<animate/>)
          ] do
        assert refused(source(@part <> "\n" <> body), design) =~ "the element"
      end
    end

    test "for an attribute that runs, styles or points outside the file", %{design: design} do
      assert refused(
               source(~s{<rect class="n-back" onclick="x()" x="1" y="1" width="1" height="1"/>}),
               design
             ) =~
               "the attribute onclick"

      assert refused(
               source(
                 ~s{<rect class="n-back" style="fill:red" x="1" y="1" width="1" height="1"/>}
               ),
               design
             ) =~
               "the attribute style"

      assert refused(
               source(~s(<rect class="n-back" fill="red" x="1" y="1" width="1" height="1"/>)),
               design
             ) =~
               "the attribute fill"

      assert refused(source(~s(<use xlink:href="https://example.com/x.svg#a"/>)), design) =~
               "the reference"

      assert refused(source(~s(<use href="other.svg#a"/>)), design) =~ "the reference"

      assert refused(
               source(
                 ~s{<line class="arr" x1="1" y1="1" x2="9" y2="1" marker-end="url(https://x/y#a)"/>}
               ),
               design
             ) =~
               "the reference"
    end

    test "for a class the skin does not have, or an id another diagram could share", %{
      design: design
    } do
      assert refused(source(~s(<rect class="red" x="1" y="1" width="1" height="1"/>)), design) =~
               "the class red"

      assert refused(
               source(~s(<rect class="n-back" id="arrow" x="1" y="1" width="1" height="1"/>)),
               design
             ) =~
               "the id arrow"
    end

    test "for a connector that is not orthogonal", %{design: design} do
      assert refused(source(~s(<line class="arr" x1="1" y1="1" x2="9" y2="9"/>)), design) =~
               "not orthogonal"

      assert refused(source(~s(<path class="arr" d="M 1,1 L 9,9"/>)), design) =~ "not orthogonal"

      assert {:ok, _svg} =
               render(source(~s(<path class="arr" d="M 1,1 H 92 Q 100,1 100,9 V 40"/>)), design)
    end

    test "for a label with no mask, and for a part drawn over a mask", %{design: design} do
      unmasked = ~s(<text class="lbl" x="180" y="60">SUBMITS</text>)

      assert refused(source(@part <> "\n" <> unmasked), design) =~
               "a label with no mask under it: SUBMITS"

      covered = ~s(<rect class="mask" x="40" y="40" width="48" height="14" rx="2"/>\n) <> @part
      assert refused(source(covered), design) =~ "a part drawn over a label's mask"
    end

    test "for more parts or connectors than the budget, the legend aside", %{design: design} do
      parts =
        Enum.map_join(0..9, "\n", fn i ->
          ~s(<rect class="n-back" x="#{i * 30}" y="1" width="20" height="20"/>)
        end)

      assert refused(source(parts), design) =~ "10 parts, more than 9"

      assert {:ok, _svg} =
               render(source(~s(<g class="legend">#{parts}</g>)), design)

      connectors =
        Enum.map_join(0..12, "\n", fn i ->
          ~s(<line class="arr" x1="1" y1="#{i}" x2="9" y2="#{i}"/>)
        end)

      assert refused(source(connectors), design) =~ "13 connectors, more than 12"
    end

    test "for a name outside the glossary, and for binding alone", %{design: design} do
      other = ~s(<text class="name" x="1" y="1">Message broker</text>)
      assert refused(source(other), design) =~ "the name Message broker"
      assert refused(source(@part, words: "application, widget"), design) =~ "the word widget"

      alone = ~s(<text class="keyt" x="1" y="1">identity · bindings · grants</text>)
      assert refused(source(alone), design) =~ ~s("binding" alone)

      qualified = ~s(<text class="keyt" x="1" y="1">resource bindings and role bindings</text>)
      assert {:ok, _svg} = render(source(qualified), design)
    end

    test "for XML that does not parse", %{design: design} do
      assert refused(source("<rect"), design) =~ "XML that does not parse"
    end
  end

  describe "fixes from the review of eh-os#522" do
    test "a connector stays orthogonal however its path is written", %{design: design} do
      for body <- [
            ~s(<path class="arr" d="M 1,1 9,9"/>),
            ~s(<path class="arr" d="M 0,0 Q 0,0 100,100"/>),
            ~s(<path class="arr" d="M 0,0 C 1,1 2,2 3,3"/>),
            ~s(<polyline class="arr" points="0,0 10,10"/>),
            ~s{<line class="arr" x1="1" y1="1" x2="9" y2="1" transform="rotate(45)"/>}
          ] do
        assert {:error, _reasons} = render(source(body), design), body
      end

      for body <- [
            ~s(<path class="arr" d="m 1,1 h 10 q 8,0 8,8 v 20"/>),
            ~s(<path class="arr" d="M 0,0 10,0 10,10"/>),
            ~s(<polyline class="arr" points="0,0 10,0 10,10"/>),
            ~s(<line class="arr" x1="0" y1="0" y2="10"/>)
          ] do
        assert {:ok, _svg} = render(source(body), design), body
      end
    end

    test "an xlink reference keeps its namespace in the output", %{design: design} do
      body = ~s(<defs><rect id="test-a" class="knock" x="1" y="1" width="1" height="1"/></defs>
<use xlink:href="#test-a"/>)

      source =
        String.replace(
          source(body),
          ~s(xmlns="http://www.w3.org/2000/svg">),
          ~s(xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink">)
        )

      assert {:ok, svg} = render(source, design)
      assert svg =~ ~s(xmlns:xlink="http://www.w3.org/1999/xlink")
      body = svg |> String.split("\n", parts: 3) |> List.last()

      assert {_doc, []} =
               :xmerl_scan.string(:binary.bin_to_list(body),
                 quiet: true,
                 namespace_conformant: true
               )
    end

    test "a namespace is declared only on the root, and only as SVG's or XLink's", %{
      design: design
    } do
      assert refused(source(~s(<g xmlns="http://www.w3.org/1999/xhtml"/>)), design) =~
               "the namespace xmlns"

      wrong =
        String.replace(
          source(@part),
          ~s(xmlns="http://www.w3.org/2000/svg"),
          ~s(xmlns="https://evil.example/")
        )

      assert refused(wrong, design) =~ "the namespace xmlns"
    end

    test "a root needs a viewBox of four numbers, commas allowed", %{design: design} do
      no_view_box = String.replace(source(@part), ~s(viewBox="0 0 400 200" ), "")
      assert refused(no_view_box, design) =~ "no viewBox of four numbers"

      commas =
        String.replace(source(@part), ~s(viewBox="0 0 400 200"), ~s(viewBox="0,0,400,200"))

      assert {:ok, svg} = render(commas, design)
      assert svg =~ ~s(width="400" height="200")
    end

    test "a diagram's id is a selector a browser reads as one id", %{design: design} do
      for id <- ["01-context", "deploy.v2", "a--b", "Context", "context\n"] do
        assert {:error, [reason]} = EhosDiagrams.render(source(@part), id, design, @vocabulary)
        assert reason =~ "a file name that is not"
      end
    end

    test "a reference points at an id the source holds", %{design: design} do
      assert refused(source(~s(<use href="#test-missing"/>)), design) =~
               "which no element holds"

      gone = ~s{<line class="arr" x1="1" y1="1" x2="9" y2="1" marker-end="url(#test-gone)"/>}
      assert refused(source(gone), design) =~ "which no element holds"
    end

    test "a label has its own position, outside any transform", %{design: design} do
      moved =
        ~s{<g transform="translate(10,0)"><rect class="mask" x="1" y="1" width="40" height="14"/><text class="lbl" x="2" y="10">SUBMITS</text></g>}

      assert refused(source(moved), design) =~
               "a transform on a connector, a label, a mask, a part, a chip or a tag"

      unplaced = ~s(<text class="lbl"><tspan class="sub" x="2" y="10">SUBMITS</tspan></text>)
      assert refused(source(unplaced), design) =~ "a label with no x and y of its own"
    end

    test "a line whose ends are not numbers is named so", %{design: design} do
      assert refused(source(~s(<line class="arr" x1="a" y1="0" x2="b" y2="10"/>)), design) =~
               "a line whose ends are not numbers"
    end

    test "a part's class belongs on a <rect>", %{design: design} do
      assert refused(source(~s(<path class="n-store" d="M 0,0 H 10"/>)), design) =~
               "a part's class on <path>"
    end

    test "a name holds a word of its header whole, and the header says binding only qualified",
         %{design: design} do
      cooperator = ~s(<text class="name" x="1" y="1">Cooperator</text>)
      assert refused(source(cooperator, words: "operator"), design) =~ "the name Cooperator"

      plural = ~s(<text class="name" x="1" y="1">Applications</text>)
      assert {:ok, _svg} = render(source(plural), design)

      assert refused(source(@part, title: "Grants and bindings"), design) =~ ~s("binding" alone)
    end

    test "a source is refused when too large, or declaring another encoding with spaces", %{
      design: design
    } do
      large = source(@part <> "\n<!-- " <> String.duplicate("x", 300_000) <> " -->")
      assert refused(large, design) =~ "more than 262144 bytes"

      spaced = ~s(<?xml version = "1.0" encoding = "ISO-8859-1"?>\n) <> source(@part)
      assert refused(spaced, design) =~ "an encoding other than UTF-8"
    end

    test "the stylesheet keeps its quotes, so it reads the same inlined into HTML", %{
      design: design
    } do
      assert {:ok, svg} = render(source(@part), design)
      refute svg =~ "&quot;Albert Sans"
      assert svg =~ ~s(--sans:"Albert Sans")
    end
  end

  describe "fixes from the second review of eh-os#522" do
    test "a path's numbers after Z are refused rather than read forever", %{design: design} do
      for d <- ["M0,0H10Z 5 5", "M0,0H10z5"] do
        assert refused(source(~s(<path class="arr" d="#{d}"/>)), design) =~ "not orthogonal"
      end
    end

    test "numbers are SVG's own, whole", %{design: design} do
      for d <- ["M.5,1 H9", "M-.5,1 h1e+1", "M1e1,0 V10"] do
        assert {:ok, _svg} = render(source(~s(<path class="arr" d="#{d}"/>)), design), d
      end

      for body <- [
            ~s(<path class="arr" d="M0,0 H10 # 20"/>),
            ~s(<polyline class="arr" points="0,.5 10,.7"/>),
            ~s(<polyline class="arr" points="0,0 10"/>),
            ~s(<line class="arr" x1="a" y1="0" x2="b" y2="10"/>),
            ~s(<line class="arr" x1="1" y1="1" y2="9"/>),
            ~s(<line class="arr" x1="" y1="0" x2="0" y2="9"/>)
          ] do
        assert {:error, _reasons} = render(source(body), design), body
      end

      for view_box <- ["0 0 10px 10px", "0 0 -5 -5", "0 0 0 10"] do
        bad = String.replace(source(@part), ~s(viewBox="0 0 400 200"), ~s(viewBox="#{view_box}"))
        assert refused(bad, design) =~ "no viewBox of four numbers", view_box
      end
    end

    test "a part is not moved by a transform either", %{design: design} do
      moved =
        ~s{<g transform="translate(5,5)"><rect class="n-back" x="1" y="1" width="10" height="10"/></g>}

      assert refused(source(moved), design) =~
               "a transform on a connector, a label, a mask, a part, a chip or a tag"
    end

    test "an XML declaration is read only at the start, and a flood of them is refused fast", %{
      design: design
    } do
      later =
        source(@part) |> String.replace("<svg ", ~s(<?xml version="1.0"?>\n<svg ), global: false)

      assert refused(later, design) =~ "a processing instruction"

      flood = String.duplicate("<?xml ", 40_000) <> source(@part)
      {micros, result} = :timer.tc(fn -> render(flood, design) end)
      assert {:error, ["a processing instruction"]} = result
      assert micros < 1_000_000
    end

    test "a trailing dot, or a number too large for a float, is refused, not a crash", %{
      design: design
    } do
      for d <- ["M1.,0 H9", "M1.e1,0 V10", "M1e400,0 H9"] do
        assert refused(source(~s(<path class="arr" d="#{d}"/>)), design) =~ "not orthogonal"
      end

      for view_box <- ["0 0 400. 200", "0 0 1e400 200"] do
        bad = String.replace(source(@part), ~s(viewBox="0 0 400 200"), ~s(viewBox="#{view_box}"))
        assert refused(bad, design) =~ "no viewBox of four numbers", view_box
      end
    end

    test "a header word is matched whole, even when it ends in a sign", %{design: design} do
      name = ~s(<text class="name" x="1" y="1">C++ runtime</text>)
      vocabulary = %{@vocabulary | words: ["c++"]}

      assert {:ok, _svg} =
               EhosDiagrams.render(source(name, words: "C++"), "test", design, vocabulary)
    end
  end

  describe "a part's maturity and every label's words (eh-os#526)" do
    @planned ~s(<rect id="test-client" class="n-back m-planned" x="40" y="40" width="120" height="60"/>
<text class="tagt" x="44" y="50">PLANNED</text>
<text class="name" x="100" y="70" text-anchor="middle">Client application</text>)

    test "a part shows its concept's badge, as an outline and a tag", %{design: design} do
      assert {:ok, _svg} = render(source(@planned, parts: "client = planned-one"), design)

      assert refused(source(@planned, parts: "client = open-one"), design) =~
               "the part client, whose outline is not open, the badge of open-one"

      untagged = String.replace(@planned, "PLANNED", "THE SYSTEM")

      assert refused(source(untagged, parts: "client = planned-one"), design) =~
               "the part client, whose tag does not name PLANNED"

      assert refused(source(@planned, parts: "client = built-one"), design) =~
               "the part client, whose outline is not built"

      tagged = String.replace(@planned, " m-planned", "")

      assert refused(source(tagged, parts: "client = built-one"), design) =~
               "the part client, which is built and tagged PLANNED"
    end

    test "a part is named in the header, by a concept its vocabulary holds or by -", %{
      design: design
    } do
      unnamed = String.replace(@part, ~s(id="test-client" ), "")
      assert refused(source(unnamed), design) =~ "a part or chip its header's parts do not name"

      assert refused(source(@part, parts: "client = nowhere"), design) =~
               "the part client, whose concept nowhere its vocabulary does not hold"

      assert refused(source(@part, parts: "client"), design) =~
               ~s(the part client in its header, with no concept after "=")

      assert refused(source(@part, parts: "client = built-one, gone = -"), design) =~
               "the part gone in its header, which it does not draw"

      assert {:ok, _svg} = render(source(@part, parts: "client = -"), design)

      assert refused(source(@planned, parts: "client = -"), design) =~
               "the part client, which stands for no concept and shows a badge"
    end

    test "a tag belongs to the smallest part around it", %{design: design} do
      inner =
        ~s(<rect id="test-inner" class="n-store m-open" x="50" y="60" width="60" height="30"/>
<text class="tagt" x="54" y="70">OPEN</text>)

      assert {:ok, _svg} =
               render(
                 source(@part <> "\n" <> inner, parts: "client = built-one, inner = open-one"),
                 design
               )
    end

    test "a tag is placed by its own x and y, inside a part or a chip", %{design: design} do
